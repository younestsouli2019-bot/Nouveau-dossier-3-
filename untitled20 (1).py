def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Check Bitcoin address balances.")
    parser.add_argument("addresses", nargs="*", help="addresses (defaults to the built-in list)")
    parser.add_argument(
        "-f", "--file", action="append", help="file with one address per line "
        "(# comments allowed); repeatable"
    )
    parser.add_argument("--stdin", action="store_true", help="also read addresses from stdin")
    parser.add_argument("--csv", help="write ranked hits to this CSV path")
    parser.add_argument("--jsonl", dest="jsonl_path", help="append hits as JSON lines (streamed)")
    parser.add_argument("--json", dest="json_path", help="write hits to this JSON path (one-shot)")
    parser.add_argument(
        "--min-btc", type=float, default=0.0,
        help="only count/report addresses holding at least this much (palpable threshold)",
    )
    parser.add_argument("--top", type=int, default=None, help="show only the N richest hits")
    parser.add_argument(
        "--hits-only", action="store_true", help="print funded hits only (no summary noise)"
    )
    parser.add_argument("--workers", type=int, default=DEFAULT_WORKERS)
    parser.add_argument("--chunk-size", type=int, default=DEFAULT_CHUNK_SIZE)
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT)
    parser.add_argument("-v", "--verbose", action="store_true")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = _build_parser().parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.WARNING,
        format="%(asctime)s %(levelname)s %(name)s: %(message)s",
    )

    min_sat = max(0, int(round(args.min_btc * SATOSHIS_PER_BTC)))

    sources = _address_source(args)
    try:
        first = next(sources)
    except StopIteration:
        first = None
    addresses: Iterable[str] = sources if first is None else _chain_one(first, sources)
    if first is None:
        addresses = DEFAULT_ADDRESSES

    summary = ScanSummary(min_sat=min_sat)
    hits: List[AddressBalance] = []
    started = time.monotonic()

    with ResultStream(csv_path=args.csv, jsonl_path=args.jsonl_path, min_sat=min_sat) as stream:
        with BlockchainInfoClient(timeout=args.timeout, chunk_size=args.chunk_size) as client:
            # Consume lazily: only hits are retained, so RAM is independent of
            # how many addresses are scanned.
            for bal in client.iter_balances(addresses, workers=args.workers):
                summary.observe(bal)
                if stream.offer(bal):
                    hits.append(bal)

    if summary.checked == 0:
        print("No addresses to check.")
        return 1

    hits.sort(key=lambda bal: bal.balance_sat or 0, reverse=True)
    print_hits(hits, top=args.top)
    if not args.hits_only:
        print_summary(summary, time.monotonic() - started)

    if args.csv:
        print(f"Wrote {stream.written} hit(s) to {args.csv}")
    if args.jsonl_path:
        print(f"Appended {stream.written} hit(s) to {args.jsonl_path}")
    if args.json_path:
        count = export_json(hits, args.json_path)
        print(f"Wrote {count} hit(s) to {args.json_path}")

    return 0 if summary.unknown == 0 else 2


def _chain_one(first: str, rest: Iterable[str]) -> Iterator[str]:
    yield first
    yield from rest


if __name__ == "__main__":
    sys.exit(main())
