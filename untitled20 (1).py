def to_dataframe(balances: Iterable[AddressBalance], *, hits_only: bool = False):
    """Build a pandas DataFrame (pandas is imported lazily)."""
    import pandas as pd

    rows = [bal.to_row() for bal in balances if not hits_only or bal.is_hit]
    columns = ["address", "balance_btc", "balance_sat", "n_tx", "tier", "error"]
    return pd.DataFrame(rows, columns=columns)


def export_csv(
    balances: Iterable[AddressBalance], path: str, *, hits_only: bool = False
) -> int:
    frame = to_dataframe(balances, hits_only=hits_only)
    frame.to_csv(path, index=False)
    return len(frame)


def export_json(
    balances: Iterable[AddressBalance], path: str, *, hits_only: bool = False
) -> int:
    rows = [bal.to_row() for bal in balances if not hits_only or bal.is_hit]
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(rows, handle, indent=2)
    return len(rows)


def _read_addresses_file(path: str) -> Iterator[str]:
    with open(path, "r", encoding="utf-8") as handle:
        for raw in handle:
            line = raw.split("#", 1)[0].strip()
            if line:
                yield line


def _address_source(args: argparse.Namespace) -> Iterator[str]:
    yield from args.addresses
    for path in args.file or []:
        yield from _read_addresses_file(path)
    if args.stdin:
        for raw in sys.stdin:
            line = raw.split("#", 1)[0].strip()
            if line:
                yield line


# --------------------------------------------------------------------------- #
# CLI
