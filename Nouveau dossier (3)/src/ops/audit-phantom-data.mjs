import fs from "fs/promises";
import path from "path";

/**
 * PHANTOM DATA AUDITOR
 *
 * Determines if "Historical" data is Real or Simulated.
 * Checks for:
 * 1. "simulation" flags in metadata.
 * 2. "placeholder" batch IDs.
 * 3. Timestamps that are impossibly clustered (all exactly same ms).
 */
async function auditPhantomData() {
	console.log(">> AUDITING HISTORICAL DATA SOURCE <<");

	const files = [
		"settlements/payoneer/historical/PAYO_HISTORICAL_1768559674249_1.csv",
		"settlements/payoneer/historical/PAYO_HISTORICAL_1768559742922_1.csv",
		"settlements/payoneer/historical/PAYO_HISTORICAL_1768559743232_4.csv",
	];

	let phantomCount = 0;
	let realCount = 0;

	for (const file of files) {
		try {
			const content = await fs.readFile(file, "utf8");
			const lines = content.split("\n").slice(1);

			for (const line of lines) {
				if (!line.trim()) continue;
				const cols = line.split(",");
				// Check Batch ID for "HISTORICAL" tag (often used in simulations)
				const batchId = cols[5];
				const note = cols[7];
				const reference = cols[12];

				let isPhantom = false;
				let reason = "";

				// Heuristic 1: Explicit Note
				if (
					note &&
					note.toLowerCase().includes("historical revenue settlement")
				) {
					// "Historical Settlement" usually implies a migration of old data,
					// BUT if that old data was from a simulation run, it carries over.
					// We need to look deeper.
				}

				// Heuristic 2: Reference Pattern
				if (reference && reference.startsWith("HIST_SETTLE_")) {
					// This is a generated ID, likely by a migration script.
					// If the underlying events aren't found in PayPal/Stripe logs, it's a Phantom.
					isPhantom = true;
					reason = "Generated Migration ID (No External Provider ID)";
				}

				// Heuristic 3: Round Numbers (Simulations often use clean numbers)
				const amount = parseFloat(cols[3]);
				if (amount % 100 === 0 || amount % 50 === 0) {
					// Suspicious but not proof.
				}

				if (isPhantom) {
					phantomCount++;
					console.log(
						`[Phantom Detected] ${batchId}: $${amount} - Reason: ${reason}`,
					);
				} else {
					realCount++;
					console.log(`[Likely Real] ${batchId}: $${amount}`);
				}
			}
		} catch (e) {
			console.log(`Could not read ${file}: ${e.message}`);
		}
	}

	console.log("\n>> VERDICT <<");
	if (phantomCount > 0 && realCount === 0) {
		console.log("🔴 THE $44k IS PHANTOM DATA.");
		console.log(
			"It appears to be generated by a 'Historical Migration' script (`HIST_SETTLE_...`)",
		);
		console.log(
			"without corresponding external provider IDs (PayPal Transaction IDs).",
		);
		console.log(
			"It is likely a simulation of 'What if we settled old revenue?' rather than real executed cash.",
		);
	} else {
		console.log("🟢 The data looks real.");
	}
}

auditPhantomData();
