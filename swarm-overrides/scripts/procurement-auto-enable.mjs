// Auto-enable rails when all required credentials are present.

const lines = ["#!/bin/bash", "# Auto-generated by procurement-auto-enable.mjs"];

function enableIf(rail, env, requiredKeys) {
  const missing = requiredKeys.filter((k) => !process.env[k]);
  if (missing.length === 0) {
    lines.push(`# ${rail}: ALL CREDS PRESENT -> auto-enabling`);
    lines.push(`export ${env}=true`);
    return true;
  }
  lines.push(`# ${rail}: missing ${missing.join(", ")} -> staying disabled`);
  return false;
}

let enabled = 0;
const total = 6;

if (enableIf("PAYPAL", "PAYPAL_ENABLED", ["PAYPAL_CLIENT_ID", "PAYPAL_CLIENT_SECRET", "PAYPAL_API_BASE_URL"])) enabled++;
if (enableIf("PAYONEER", "PAYONEER_ENABLE", ["PAYONEER_API_BASE", "PAYONEER_CLIENT_ID", "PAYONEER_CLIENT_SECRET", "PAYONEER_PROGRAM_ID", "PAYONEER_OWNER_ID"])) enabled++;
if (enableIf("PLAID", "PLAID_ENABLE", ["PLAID_CLIENT_ID", "PLAID_SECRET"])) enabled++;
if (enableIf("WISE", "WISE_ENABLE", ["WISE_API_TOKEN"])) enabled++;
if (enableIf("CRYPTO", "CRYPTO_WITHDRAW_ENABLE", ["TRUST_WALLET_ADDRESS"])) enabled++;
if (enableIf("BANKING_CIRCLE", "BANKING_CIRCLE_ENABLE", ["BANKING_CIRCLE_CLIENT_ID", "BANKING_CIRCLE_CLIENT_SECRET"])) enabled++;

lines.push(`# Auto-enable complete: ${enabled}/${total} rails ready`);

import { writeFileSync } from "node:fs";
writeFileSync(process.env.OUTPUT_PATH || "/tmp/rail-enables.sh", lines.join("\n") + "\n");
console.log(`[auto-enable] wrote ${lines.length} lines to ${process.env.OUTPUT_PATH || "/tmp/rail-enables.sh"}`);
console.log(`[auto-enable] ${enabled}/${total} rails auto-enabled`);
for (const l of lines) console.log("  " + l);
