def start_virtual_display(
    display: str = XVFB_DISPLAY, geometry: str = XVFB_GEOMETRY
) -> Optional[subprocess.Popen]:
    """Start an Xvfb display; returns its process."""
    existing = os.environ.get("DISPLAY")
    if existing:
        log(f"\u2705 Reusing existing DISPLAY={existing}")
        return None

    if shutil.which("Xvfb") is None:
        try:
            subprocess.check_call(["apt-get", "install", "-y", "xvfb"])
        except Exception as exc:  # noqa: BLE001
            log(f"\u26a0\ufe0f Could not install Xvfb: {exc}")
            return None

    lock_file = f"/tmp/.X{display.lstrip(':')}-lock"
    try:
        os.remove(lock_file)
    except FileNotFoundError:
        pass

    process = subprocess.Popen(
        ["Xvfb", display, "-screen", "0", geometry],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    time.sleep(1.0)
    if process.poll() is not None:
        log("\u26a0\ufe0f Xvfb exited immediately; FAIL-CLOSED.")
        sys.exit(1)

    os.environ["DISPLAY"] = display
    log(f"\u2705 Virtual display {display} ready.")
    return process

