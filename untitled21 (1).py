class BotSupervisor:
    """Runs the bot with exponential backoff and Fail-closed monitoring."""

    def __init__(
        self,
        project_dir: str,
        args: Sequence[str] = BOT_ARGS,
        *,
        base_backoff: float = BASE_BACKOFF,
        max_backoff: float = MAX_BACKOFF,
        healthy_after: float = HEALTHY_AFTER,
        max_restarts: Optional[int] = None,
        log_path: Optional[str] = None,
    ) -> None:
        self.project_dir = project_dir
        self.args = list(args)
        self.env = os.environ.copy()
        self.env.update({
            "PYTHONPATH": project_dir,
            "RECEIVER_UID": RECEIVER_UID,
            "RECEIVER_NICKNAME": RECEIVER_NICKNAME,
            "AUDIT_INTEGRITY": "1",
            "PYTHONUNBUFFERED": "1"
        })
        self.base_backoff = base_backoff
        self.max_backoff = max_backoff
        self.healthy_after = healthy_after
        self.max_restarts = max_restarts
        self.log_path = log_path

        self._process: Optional[subprocess.Popen] = None
        self._stopping = False
        self.restarts = 0

    def request_stop(self, *_signum: object) -> None:
        self._stopping = True
        self._terminate_child()

    def _terminate_child(self, grace: float = 10.0) -> None:
        process = self._process
        if process is None or process.poll() is not None:
            return
        log("Sending SIGTERM to bot...", sign=True)
        process.terminate()
        try:
            process.wait(timeout=grace)
        except subprocess.TimeoutExpired:
            log("SIGTERM timed out; sending SIGKILL.", sign=True)
            process.kill()

    def _spawn(self) -> subprocess.Popen:
        return subprocess.Popen(
            [sys.executable, *self.args],
            cwd=self.project_dir,
            env=self.env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )

    def _emit(self, line: str) -> None:
        sys.stdout.write(line)
        sys.stdout.flush()
        if self.log_path:
            with open(self.log_path, "a", encoding="utf-8") as handle:
                handle.write(line)

    def _pump(self, process: subprocess.Popen) -> None:
        assert process.stdout is not None
        for line in process.stdout:
            self._emit(line)
            # Proactive health check: if output stops for too long or signals
            # a crash, we could intercept here.
        process.stdout.close()

    def _sleep(self, seconds: float) -> None:
        deadline = time.monotonic() + seconds
        while not self._stopping and time.monotonic() < deadline:
            time.sleep(min(0.5, deadline - time.monotonic()))

    def run(self) -> int:
        backoff = self.base_backoff
        last_returncode = 0
        while not self._stopping:
            started = time.monotonic()
            try:
                self._process = self._spawn()
                log(f"\u25b6\ufe0f Bot started (pid {self._process.pid}, restart #{self.restarts})", sign=True)
                self._pump(self._process)
                last_returncode = self._process.wait()
            except Exception as exc:
                log(f"\u274c Failed to spawn bot: {exc}", sign=True)
                last_returncode = -1

            uptime = time.monotonic() - started
            if self._stopping:
                log(f"\u23f9\ufe0f Supervisor stopping (exit {last_returncode}).", sign=True)
                break

            if self.max_restarts is not None and self.restarts >= self.max_restarts:
                log(f"\u274c Max restarts ({self.max_restarts}) reached; FAIL-CLOSED.", sign=True)
                break

            if uptime >= self.healthy_after:
                backoff = self.base_backoff

            self.restarts += 1
            log(f"\u26a0\ufe0f Bot exited (code {last_returncode}) after {uptime:.1f}s. Retrying in {backoff:.0f}s...", sign=True)
            self._sleep(backoff)
            backoff = min(backoff * 2, self.max_backoff)

        self._terminate_child()
        return last_returncode

