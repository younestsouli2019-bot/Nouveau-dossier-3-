def generate_audit_manifest(project_dir: str) -> str:
    """Create an HMAC-signed manifest of the project structure."""
    manifest = {
        "timestamp": time.time(),
        "files": {},
        "identity": RECEIVER_UID
    }
    for root, _, files in os.walk(project_dir):
        if ".git" in root or "__pycache__" in root:
            continue
        for f in files:
            path = os.path.join(root, f)
            rel = os.path.relpath(path, project_dir)
            try:
                with open(path, "rb") as fh:
                    manifest["files"][rel] = hashlib.sha256(fh.read()).hexdigest()
            except Exception:
                continue
    
    data = json.dumps(manifest, sort_keys=True)
    sig = sign_data(data, get_machine_secret())
    manifest_path = os.path.join(tempfile.gettempdir(), "audit_manifest.json")
    with open(manifest_path, "w") as fh:
        json.dump({"payload": manifest, "signature": sig}, fh, indent=2)
    log(f"\u2705 Audit manifest generated: {sig[:16]}...", sign=True)
    return manifest_path

