import fs from "node:fs";
import path from "node:path";
import PDFDocument from "pdfkit";

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function main() {
  const dir = path.resolve(process.cwd(), "catalogue");
  ensureDir(dir);
  const outPdf = path.join(dir, "catalogue_master.pdf");
  const doc = new PDFDocument({ margin: 50 });
  const stream = fs.createWriteStream(outPdf);
  doc.pipe(stream);
  doc.fontSize(28).text("Catalogue 2026", { align: "center" });
  doc.moveDown(2);
  doc.fontSize(14).text("Placeholder output generated by Swarm.", { align: "center" });
  doc.moveDown(2);
  doc.text(`Generated at: ${new Date().toISOString()}`, { align: "center" });
  doc.end();
  stream.on("finish", () => {
    process.stdout.write(JSON.stringify({ ok: true, outPdf }) + "\n");
  });
}

main();
