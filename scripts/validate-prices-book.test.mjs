import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/**
 * Price-book contract guard.
 *
 * Regression this exists for: commit 690abde rewrote prices.json down to 10 of
 * the 298 course entries, deleting 1442 lines, and nothing failed. An entry
 * absent from `courses` means "not for sale" (see ./README.md), so those 288
 * slugs silently became `404 course_not_found` from POST /api/orders — the
 * original zero-revenue failure, committed to a branch unchecked.
 *
 * The book's contract is ../README.md in that directory: it is the ONLY
 * permitted source of a course price, prices are never generated by code, and
 * `approvedBy`/`approvedAt` record a commercial commitment rather than
 * decorate it.
 *
 * RWC_PRICE_BOOK overrides the path, so a second currency's book (README rule
 * 2) or a fixture can be checked with the same rules.
 */

const DEFAULT_BOOK = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'rank',
  'output',
  'data',
  'pricing',
  'prices.json',
);
const BOOK_PATH = process.env.RWC_PRICE_BOOK ?? DEFAULT_BOOK;

// The catalog carries 298 courses. A book far below that is a wipe, not a
// curation: 250 is the floor, not the target.
const MIN_COURSES = 250;
const MIN_QUOTE_REQUIRED = 200;

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;
const CURRENCY = /^[A-Z]{3}$/;
const MODES = ['fixed', 'quote_required'];

function loadBook() {
  expect(existsSync(BOOK_PATH), `price book missing: ${BOOK_PATH}`).toBe(true);
  // Strip a BOM: PowerShell redirection adds one, and JSON.parse rejects it.
  return JSON.parse(readFileSync(BOOK_PATH, 'utf8').replace(/^\uFEFF/, ''));
}

const book = loadBook();
const courses = book.courses ?? {};
const slugs = Object.keys(courses);
const fixed = slugs.filter((s) => courses[s]?.mode === 'fixed');
const quoteRequired = slugs.filter((s) => courses[s]?.mode === 'quote_required');

describe('price book shape', () => {
  it('declares schemaVersion 1 and a usable currency', () => {
    expect(book.schemaVersion).toBe(1);
    expect(book.currency, `currency: ${book.currency}`).toMatch(CURRENCY);
    expect(Number.isInteger(book.minorUnits) && book.minorUnits > 0).toBe(true);
  });

  it('still carries the whole catalog, not a subset', () => {
    expect(slugs.length, `${slugs.length} courses in ${BOOK_PATH}`).toBeGreaterThanOrEqual(
      MIN_COURSES,
    );
  });

  it('keeps the quote pipeline populated', () => {
    expect(quoteRequired.length).toBeGreaterThanOrEqual(MIN_QUOTE_REQUIRED);
  });

  it('uses only the two documented modes', () => {
    const unknown = slugs.filter((s) => !MODES.includes(courses[s]?.mode));
    expect(unknown, `unknown mode on: ${unknown.join(', ')}`).toEqual([]);
  });
});

describe('every entry records a real commercial decision', () => {
  it('has a non-empty approvedBy', () => {
    const missing = slugs.filter(
      (s) => typeof courses[s]?.approvedBy !== 'string' || courses[s].approvedBy.trim() === '',
    );
    expect(missing, `no approvedBy on: ${missing.join(', ')}`).toEqual([]);
  });

  it('has an approvedAt in strict YYYY-MM-DD form', () => {
    // An ISO timestamp fails here on purpose: the contract is a date, and
    // accepting "2026-10-18T10:41:15Z" would let a machine-stamped value pass
    // as a human approval.
    const bad = slugs.filter((s) => !ISO_DATE.test(courses[s]?.approvedAt ?? ''));
    expect(bad, `bad approvedAt on: ${bad.join(', ')}`).toEqual([]);
  });
});

describe('amounts match the mode', () => {
  it('publishes a positive integer amount on every fixed entry', () => {
    // A zero or float price would reach SalesLedger, whose
    // salesledger_amount_positive CHECK requires priceAmountCents > 0.
    const bad = fixed.filter((s) => {
      const a = courses[s]?.amountMinor;
      return !Number.isInteger(a) || a <= 0;
    });
    expect(bad, `fixed without a positive amountMinor: ${bad.join(', ')}`).toEqual([]);
  });

  it('publishes no amount on a quote_required entry', () => {
    const bad = quoteRequired.filter((s) => courses[s]?.amountMinor !== undefined);
    expect(bad, `amountMinor leaked onto a quote_required entry: ${bad.join(', ')}`).toEqual([]);
  });

  it('keeps the owner-approved PPL preptest price intact', () => {
    // The one price the owner has actually authorised. A silent change to this
    // number changes what a buyer is charged, so it is asserted by name.
    const ppl = courses['private-pilot-license-ppl-preptest-2025'];
    expect(ppl, 'PPL preptest entry is missing').toBeDefined();
    expect(ppl.mode).toBe('fixed');
    expect(ppl.amountMinor).toBe(25000);
  });
});
